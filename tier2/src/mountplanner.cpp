#include "hsg100/mountplanner.hpp"
#include "hsg100/keyvalues.hpp"

#include <sstream>

namespace hsg100 {

MountPlan planMount(const ModInfo &mi, const std::string &modGameDir, uint32_t baseGameId) {
    MountPlan plan;
    plan.modGameDir = modGameDir;

    if (modGameDir.empty()) {
        plan.warnings.push_back("mod game dir name is empty");
        return plan;
    }

    // ---- collect the mod's own declared search paths -----------------------
    // We re-parse the original gameinfo if the classifier found one (path in
    // notes[0] convention) — but the classifier already discarded layout
    // details, so the extractor passes the raw text through ModInfo::notes?
    // No: keep the contract clean. The extractor writes the ORIGINAL file to
    // gameinfo.txt.orig and hands planMount the text via originalGameinfo().
    plan.warnings.push_back("original gameinfo preserved as gameinfo.txt.orig");

    // Base search path set every mod gets, in order:
    //   1. the mod itself (highest priority)
    //   2. |gameinfo_path| relative extras the mod declared (content)
    //   3. base HL2 content, platform — LAST so base code never overrides mod
    //      content, and mod content never breaks base fallback.
    std::ostringstream o;
    o << "\"gameinfo\"\n{\n";
    o << "\t// generated by half-sourceG100 mount planner (Tier 2)\n";
    o << "\tgame \"" << (mi.game.empty() ? modGameDir : mi.game) << "\"\n";
    o << "\ttitle \"" << mi.modName << "\"\n";
    o << "\ttitle2 \"\"\n";
    o << "\ttype \"singleplayer_only\"\n";
    o << "\tSteamAppId \"" << baseGameId << "\"\n";
    o << "\n\tfilesystem\n\t{\n";
    o << "\t\tSteamAppId\t\t\"" << baseGameId << "\"\n";
    o << "\t\tToolsAppId\t\t\"211\"\n";
    o << "\n\t\tSearchPaths\n\t\t{\n";
    o << "\t\t\tGame\t\t|" << modGameDir << "|\n";
    o << "\t\t\tGame\t\t|" << modGameDir << "|*_dir.vpk\n";
    // content dirs commonly shipped loose by mods — all mounted explicitly
    for (const char *d : {"maps", "materials", "models", "sound", "resource", "scripts", "particles", "cfg"}) {
        o << "\t\t\tGame\t\t|" << modGameDir << "|" << d << "\n";
    }
    // base content last
    o << "\t\t\tGame\t\t|hl2|\n";
    o << "\t\t\tGame\t\t|hl2|hl2_textures_dir.vpk\n";
    o << "\t\t\tGame\t\t|hl2|hl2_sound_misc_dir.vpk\n";
    o << "\t\t\tGame\t\t|hl2|hl2_sound_vo_english_dir.vpk\n";
    o << "\t\t\tGame\t\t|platform|\n";
    o << "\t\t}\n\t}\n}\n";

    plan.gameinfoText = o.str();

    // warnings that describe the compat contract for this mod class
    switch (mi.modClass) {
        case ModClass::SourceMod:
            plan.warnings.push_back("SOURCE_MOD: mount plan assumes Tier-1 native "
                                    "client/server .so will be built and placed in "
                                    + modGameDir + "/bin/ before this mod is fully playable");
            break;
        case ModClass::DllOnly:
            plan.warnings.push_back("DLL_ONLY: mod code (client.dll/server.dll) will NOT run; "
                                    "base HL2 code is the fallback — expect scripted-entity "
                                    "differences, content (maps/models/materials) fully mounted");
            break;
        case ModClass::ContentOnly:
            plan.warnings.push_back("CONTENT_ONLY: full compatibility expected");
            break;
        case ModClass::StandaloneTc:
            plan.warnings.push_back("STANDALONE_TC: run the TC extractor first, then re-classify");
            break;
        case ModClass::Empty:
        case ModClass::BrokenGameinfo:
            plan.warnings.push_back("nothing to mount: mod is empty or broken");
            return plan;
    }

    plan.ok = true;
    return plan;
}

} // namespace hsg100
