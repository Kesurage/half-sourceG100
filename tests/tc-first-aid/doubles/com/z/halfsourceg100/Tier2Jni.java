package com.z.halfsourceg100;

import java.util.ArrayList;
import java.util.List;

/**
 * TEST DOUBLE (tests/tc-first-aid) — shadows the real Tier2Jni ONLY inside
 * this test's javac invocation. Surface must mirror android-app/src/.../
 * Tier2Jni.java. Behavior is controllable for coverage:
 *
 *   -Dtest.planner=off   plan() reports !ok  -> TcFirstAid uses its Java fallback
 *   -Dtest.planner=on    plan() reports ok with a C++-planner-shaped text
 *   -Dtest.tier2=off     available() == false (classifier and planner gone)
 */
public final class Tier2Jni {

    public static class Result {
        public String modClass = "EMPTY";
        public String game = "";
        public String title = "";
        public String lineage = "";
        public int steamAppId;
        public boolean hasWindowsDlls, hasSourceCode, hasStandaloneEngine;
        public ArrayList<String> vpks = new ArrayList<>();
        public ArrayList<String> notes = new ArrayList<>();
        public boolean ok;
        public String gameinfoText = "";
        public ArrayList<String> warnings = new ArrayList<>();
    }

    private Tier2Jni() {}

    public static boolean available() {
        return !"off".equals(System.getProperty("test.tier2"));
    }

    public static String classifyDir(String path) { return "{}"; }

    public static Result classify(String path) {
        Result r = new Result();
        // realistic for a folder without gameinfo.txt: no metadata found;
        // the real C++ classifier reads the mod's own gameinfo (none here)
        r.modClass = "CONTENT_ONLY";
        r.game = "";
        r.title = "";
        return r;
    }

    public static Result plan(String modClass, String modDir, String game, String title,
                              int appId, List<String> vpks) {
        Result r = new Result();
        if ("on".equals(System.getProperty("test.planner"))) {
            r.ok = true;
            r.gameinfoText = "\"gameinfo\"\n{\n"
                    + "\t// generated by half-sourceG100 mount planner (Tier 2, rev 3)\n"
                    + "\tgame \"" + game + "\"\n"
                    + "\ttitle \"" + title + "\"\n"
                    + "\ttitle2 \"\"\n"
                    + "\ttype \"singleplayer_only\"\n"
                    + "\tSteamAppId \"220\"\n"
                    + "\n\tfilesystem\n\t{\n"
                    + "\t\tSteamAppId\t\t\"220\"\n"
                    + "\t\tToolsAppId\t\t\"211\"\n"
                    + "\n\t\tSearchPaths\n\t\t{\n"
                    + "\t\t\tGame\t\t|gameinfo_path|.\n"
                    + "\t\t\tGame\t\thl2\n"
                    + "\t\t\tGame\t\t|all_source_engine_paths|hl2\n"
                    + "\t\t\tGame\t\t|all_source_engine_paths|platform\n"
                    + "\t\t}\n\t}\n}\n";
            r.warnings.add("planner-double was used");
        }
        return r;
    }

    public static String version() { return "test-double"; }
}
