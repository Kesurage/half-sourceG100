package com.z.halfsourceg100;

import android.util.Log;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Scanner;

/**
 * TC first aid (v0.6.0) — makes hand-dropped TC mods actually launch.
 *
 * WHY THIS EXISTS — the two ways every TC mod died while base HL2 worked:
 *
 * 1) THE ARGV BUG (the crash). The bundled engine's Android entry
 *    (launcher/android/main.cpp, SetLauncherArgs) tokenizes the whole argument
 *    string with strtok(argv, " ") — it has NO notion of quoting. Our glue
 *    sends argv as "-game <gamedir> -console ...", so a gamedir with a space
 *    ("Minerva Metastasis") is split into "-game Minerva" + a stray
 *    "Metastasis" token. The engine then chdir()s to /sdcard/srceng, looks for
 *    Minerva/gameinfo.txt, doesn't find it, and calls the fatal
 *    Error("Setup file 'gameinfo.txt' doesn't exist ...") — the process dies
 *    before a single frame. Base games never contain spaces (hl2, episodic,
 *    ep2), which is exactly why they always worked and every TC crashed.
 *    Symlinks are not creatable on Android shared storage (FUSE), so the fix
 *    is a one-time folder rename to an argv-safe name. (The engine fork also
 *    carries a quote-aware tokenizer now — see docs/ENGINE-PACK.md — but the
 *    pinned v1.17.0025 binary predates it, so the launcher must not rely on
 *    quoting.)
 *
 * 2) PC-GAMEINFO DRIFT (the silent breakage). A TC copied straight from a PC
 *    install carries its original gameinfo.txt: "../hl2" search paths,
 *    Steam-era tokens that expand to nothing, no hl2 fallback, SteamAppId of
 *    a game we are not. The engine-valid form is regenerated by the SAME C++
 *    mount planner the importer uses (Tier2Jni.plan — rev-3 tokens), with the
 *    original preserved as gameinfo.pc.txt. A Java fallback generator (same
 *    emission shape) covers the case where libtier2jni is missing.
 */
final class TcFirstAid {

    private static final String TAG = "half-sourceG100";

    /** Marker line the tier2 C++ mount planner writes into generated gameinfo. */
    static final String PLANNER_MARKER = "generated by half-sourceG100 mount planner";

    /**
     * argv-safe gamedir: the engine tokenizer splits on spaces and treats a
     * leading '-'/'+' as a switch, so the name must be a single token that
     * cannot be mistaken for one. Base games (hl2, episodic, ep2) pass.
     */
    static boolean needsRename(String dirName) {
        if (dirName == null || dirName.isEmpty()) return true;
        if (!dirName.matches("[A-Za-z0-9][A-Za-z0-9._-]*")) return true;
        return dirName.contains("..");
    }

    /** Engine-owned first-level dirs — a TC must never live under these names. */
    static boolean isReserved(String dirName) {
        if (dirName == null) return false;
        for (String r : ModScanner.RESERVED)
            if (dirName.equalsIgnoreCase(r)) return true;
        return false;
    }

    /** Normalize any folder name into an argv-safe, filesystem-safe one. */
    static String safeName(String dirName) {
        String n = dirName == null ? "" : dirName.trim().toLowerCase(Locale.ROOT);
        StringBuilder b = new StringBuilder();
        for (char c : n.toCharArray()) {
            boolean ok = (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')
                    || c == '_' || c == '-' || c == '.';
            b.append(ok ? c : '_');
        }
        String out = b.toString();
        // collapse separator runs, strip them at the edges, kill dot-dots
        out = out.replaceAll("_+", "_").replaceAll("^[_.-]+", "").replaceAll("[_.-]+$", "");
        out = out.replace("..", "_");
        if (out.isEmpty()) out = "tc";
        // never collide with reserved roots
        for (String r : ModScanner.RESERVED)
            if (out.equals(r)) out = out + "_mod";
        return out;
    }

    static class Result {
        /** final dir name after an optional rename (never null on success) */
        String dirName;
        /** set when the folder had to be renamed (old -> dirName) */
        String renamedFrom;
        /** human summary of the gameinfo treatment, null when untouched */
        String gameinfoSummary;
        /** non-null => cannot launch; user-readable reason */
        String failReason;
    }

    private TcFirstAid() {}

    /**
     * Prepare a TC dir for launch: rename to an argv-safe name when needed,
     * then make sure gameinfo.txt is engine-valid. Idempotent.
     */
    static Result prepare(String dirName) {
        Result r = new Result();
        File dir = new File(ModScanner.ROOT, dirName);
        if (!dir.isDirectory()) {
            r.failReason = "srceng/" + dirName + " does not exist (removed?) — rescan and retry";
            return r;
        }

        // ---- 1. argv-safe, non-reserved dir name -------------------------
        String finalName = dirName;
        if (needsRename(dirName) || isReserved(dirName)) {
            String target = uniqueTarget(safeName(dirName));
            File to = new File(ModScanner.ROOT, target);
            if (!dir.renameTo(to)) {
                r.failReason = "This mod's folder name breaks the engine's command line:\n\n"
                        + dirName + "\n\nIt must be renamed to '" + target + "' but the "
                        + "rename failed (storage permission?). Rename the folder manually "
                        + "with a file manager (letters, digits, _ and - only) and rescan.";
                Log.e(TAG, "TC rename failed: " + dirName + " -> " + target);
                return r;
            }
            Log.i(TAG, "TC renamed for argv safety: " + dirName + " -> " + target);
            r.renamedFrom = dirName;
            finalName = target;
            dir = to;
        }
        r.dirName = finalName;

        // ---- 2. engine-valid gameinfo ------------------------------------
        File gi = new File(dir, "gameinfo.txt");
        if (!gi.isFile() && !hasModContent(dir)) {
            r.failReason = "srceng/" + finalName + " is not a mod: no gameinfo.txt and no "
                    + "content (maps/, VPKs, materials/, models/, sound/, resource/, "
                    + "scripts/, scenes/) found.";
            return r;
        }
        try {
            r.gameinfoSummary = fixGameinfo(dir);
        } catch (Exception e) {
            r.failReason = "gameinfo first aid failed: "
                    + (e.getMessage() != null ? e.getMessage() : e.toString());
            return r;
        }
        if (!gi.isFile()) {
            r.failReason = "srceng/" + finalName + "/ has no gameinfo.txt and none could be "
                    + "generated — the folder does not look like a mod (no gameinfo, no content).";
            return r;
        }
        return r;
    }

    /**
     * Content that makes a folder a mod worth a gamedir: mounted content
     * dirs, root VPKs, or loose maps. A gameinfo.txt alone also counts (the
     * mod declared itself a TC) — checked by the caller.
     */
    static boolean hasModContent(File dir) {
        String[] contentDirs = {"maps", "materials", "models", "sound", "resource",
                "scripts", "scenes", "particles"};
        for (String c : contentDirs)
            if (new File(dir, c).isDirectory()) return true;
        File[] kids = dir.listFiles();
        if (kids != null)
            for (File f : kids)
                if (f.isFile() && f.getName().toLowerCase(Locale.ROOT).endsWith(".vpk"))
                    return true;
        File maps = new File(dir, "maps");
        File[] bsp = maps.listFiles((f, n) -> n.toLowerCase(Locale.ROOT).endsWith(".bsp"));
        return bsp != null && bsp.length > 0;
    }

    /** A non-clashing target name for the renamed folder. */
    private static String uniqueTarget(String base) {
        String t = base;
        int i = 2;
        while (new File(ModScanner.ROOT, t).exists()) t = base + "-" + (i++);
        return t;
    }

    // ---------------------------------------------------------- gameinfo --

    /**
     * Guarantee <tc>/gameinfo.txt is the engine-valid form.
     * Returns a human summary when the file was (re)written, null when it was
     * already ours / already valid-and-marked.
     */
    static String fixGameinfo(File dir) throws IOException {
        File gi = new File(dir, "gameinfo.txt");
        String original = gi.isFile() ? readText(gi) : null;

        if (original != null && original.contains(PLANNER_MARKER)) {
            // ours already (importer or a previous launch); possibly add the
            // episodic fallback lines added in v0.6.0
            return ensureEpisodicLines(gi, original);
        }

        // metadata from the original (display only — mount facts win)
        String game = kvValue(original, "game");
        String title = kvValue(original, "title");
        if (title == null || title.isEmpty()) title = kvValue(original, "title2");
        if (title == null || title.isEmpty()) title = game;
        String type = kvType(original);

        // classify the folder on disk (same library the catalog uses)
        Tier2Jni.Result info = Tier2Jni.available()
                ? Tier2Jni.classify(dir.getAbsolutePath()) : null;
        String modClass = info != null && info.modClass != null ? info.modClass : "CONTENT_ONLY";
        if (game == null || game.isEmpty()) game = info != null ? info.game : null;
        if (game == null || game.isEmpty()) game = dir.getName();
        if (title == null || title.isEmpty()) title = info != null ? info.title : null;
        if (title == null || title.isEmpty()) title = dir.getName();

        // the mod's own root VPKs (mount names; _dir stripped, chunks skipped)
        List<String> vpks = rootVpkMounts(dir);

        String text = null;
        List<String> warnings = new ArrayList<>();
        if (Tier2Jni.available()) {
            Tier2Jni.Result plan = Tier2Jni.plan(modClass, dir.getName(), game, title, 220, vpks);
            if (plan.ok && plan.gameinfoText != null && !plan.gameinfoText.isEmpty()) {
                text = plan.gameinfoText;
                if (plan.warnings != null) warnings.addAll(plan.warnings);
            }
        }
        if (text == null) {
            text = fallbackGameinfo(dir.getName(), game, title, vpks);
            warnings.add("tier2 planner unavailable — Java fallback gameinfo written");
        }

        // carry the original's multiplayer type when it was explicit
        if (type != null) text = text.replace("type \"singleplayer_only\"", "type \"" + type + "\"");

        // base-game fallbacks for Ep1/Ep2-lineage mods
        text = addEpisodicLines(text);

        // preserve the original for the user (never overwrite an earlier backup)
        if (original != null && !original.trim().isEmpty()) {
            File backup = new File(dir, "gameinfo.pc.txt");
            if (!backup.isFile()) writeText(backup, original);
        }
        writeText(gi, text);

        StringBuilder sb = new StringBuilder();
        sb.append(original == null
                ? "gameinfo.txt was missing — generated"
                : "gameinfo.txt regenerated for the Android engine (original saved as gameinfo.pc.txt)");
        if (!warnings.isEmpty()) for (String w : warnings) sb.append("\n\u00b7 ").append(w);
        if (!vpks.isEmpty()) sb.append("\n\u00b7 ").append(vpks.size()).append(" VPK(s) mounted");
        return sb.toString();
    }

    /**
     * v0.6.0: our own generated gameinfos gain the episodic/ep2 fallback
     * lines when that content exists, so Ep1/Ep2-lineage TCs find their
     * props/materials without any manual editing.
     */
    private static String ensureEpisodicLines(File gi, String ours) throws IOException {
        if (ours.contains("|all_source_engine_paths|episodic")) return null;
        String patched = addEpisodicLines(ours);
        if (patched.equals(ours)) return null;
        writeText(gi, patched);
        return "gameinfo.txt updated: Ep1/Ep2 content fallback added";
    }

    /**
     * Insert episodic/ep2 search paths (both engine-valid forms) directly
     * before the platform line — i.e. after every hl2 line — but only when
     * those folders actually exist in the content root.
     */
    static String addEpisodicLines(String text) {
        StringBuilder add = new StringBuilder();
        if (new File(ModScanner.ROOT, "episodic").isDirectory())
            add.append("\t\t\tGame\t\tepisodic\n")
               .append("\t\t\tGame\t\t|all_source_engine_paths|episodic\n");
        if (new File(ModScanner.ROOT, "ep2").isDirectory())
            add.append("\t\t\tGame\t\tep2\n")
               .append("\t\t\tGame\t\t|all_source_engine_paths|ep2\n");
        if (add.length() == 0) return text;
        String platformLine = "\t\t\tGame\t\t|all_source_engine_paths|platform";
        int i = text.indexOf(platformLine);
        if (i < 0) return text + add;
        return text.substring(0, i) + add + text.substring(i);
    }

    /** Root-level VPK files of a mod dir as gameinfo mount names. */
    static List<String> rootVpkMounts(File dir) {
        List<String> out = new ArrayList<>();
        File[] kids = dir.listFiles();
        if (kids == null) return out;
        Arrays.sort(kids, (a, b) -> a.getName().compareToIgnoreCase(b.getName()));
        for (File f : kids) {
            if (!f.isFile()) continue;
            String m = vpkMountName(f.getName());
            if (!m.isEmpty()) out.add(m);
        }
        return out;
    }

    /** vpkMountName twin of tier2/src/mountplanner.cpp (no _dir suffix, no chunks). */
    static String vpkMountName(String file) {
        if (file == null) return "";
        String low = file.toLowerCase(Locale.ROOT);
        if (!low.endsWith(".vpk")) return "";
        String stem = file.substring(0, file.length() - 4);
        int dot = stem.lastIndexOf('.');
        if (dot >= 0 && stem.length() - dot - 1 == 3) {
            boolean digits = true;
            for (int i = dot + 1; i < stem.length(); i++)
                if (!Character.isDigit(stem.charAt(i))) { digits = false; break; }
            if (digits) return ""; // numbered chunk archive — mounts via its _dir
        }
        if (stem.length() > 4 && stem.substring(stem.length() - 4).equalsIgnoreCase("_dir"))
            stem = stem.substring(0, stem.length() - 4);
        return stem + ".vpk";
    }

    /**
     * Java fallback generator — byte-for-byte the same emission shape as the
     * C++ planner (tier2/src/mountplanner.cpp rev 3). Only used when
     * libtier2jni is missing; the planner remains the single source of truth.
     */
    static String fallbackGameinfo(String modDir, String game, String title, List<String> vpks) {
        StringBuilder o = new StringBuilder();
        o.append("\"gameinfo\"\n{\n");
        o.append("\t// generated by half-sourceG100 mount planner (Tier 2, rev 3)\n");
        o.append("\tgame \"").append(escapeKv(game.isEmpty() ? modDir : game)).append("\"\n");
        o.append("\ttitle \"").append(escapeKv(title)).append("\"\n");
        o.append("\ttitle2 \"\"\n");
        o.append("\ttype \"singleplayer_only\"\n");
        o.append("\tSteamAppId \"220\"\n");
        o.append("\n\tfilesystem\n\t{\n");
        o.append("\t\tSteamAppId\t\t\"220\"\n");
        o.append("\t\tToolsAppId\t\t\"211\"\n");
        o.append("\n\t\tSearchPaths\n\t\t{\n");
        o.append("\t\t\tGame\t\t|gameinfo_path|.\n");
        for (String m : vpks) o.append("\t\t\tGame\t\t|gameinfo_path|").append(m).append("\n");
        o.append("\t\t\tGame\t\thl2\n");
        o.append("\t\t\tGame\t\t|all_source_engine_paths|hl2\n");
        o.append("\t\t\tGame\t\t|all_source_engine_paths|hl2/hl2_textures.vpk\n");
        o.append("\t\t\tGame\t\t|all_source_engine_paths|hl2/hl2_sound_misc.vpk\n");
        o.append("\t\t\tGame\t\t|all_source_engine_paths|hl2/hl2_sound_vo_english.vpk\n");
        o.append("\t\t\tGame\t\t|all_source_engine_paths|platform\n");
        o.append("\t\t}\n\t}\n}\n");
        return o.toString();
    }

    static String escapeKv(String s) {
        if (s == null) return "";
        return s.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\n", "\\n").replace("\t", "\\t");
    }

    // ------------------------------------------------------------ kv mini --

    /** Tiny gameinfo scan: first quoted-or-bare value for a key (ModImporter twin). */
    static String kvValue(String text, String key) {
        if (text == null) return null;
        try (Scanner sc = new Scanner(text)) {
            while (sc.hasNextLine()) {
                String line = sc.nextLine();
                int ci = line.indexOf("//");
                if (ci >= 0) line = line.substring(0, ci);
                line = line.trim();
                if (!line.startsWith(key)) continue;
                String rest = line.substring(key.length()).trim();
                if (rest.isEmpty()) continue;
                if (rest.startsWith("\"")) {
                    int end = rest.indexOf('"', 1);
                    if (end > 1) return rest.substring(1, end);
                } else {
                    int end = 0;
                    while (end < rest.length() && !Character.isWhitespace(rest.charAt(end))) end++;
                    if (end > 0) return rest.substring(0, end);
                }
            }
        }
        return null;
    }

    /** The original's explicit type, when it is one of the two real values. */
    static String kvType(String text) {
        String t = kvValue(text, "type");
        if (t == null) return null;
        t = t.trim().toLowerCase(Locale.ROOT);
        return ("singleplayer_only".equals(t) || "multiplayer_only".equals(t)) ? t : null;
    }

    // ------------------------------------------------------------- file io --

    static String readText(File f) throws IOException {
        try (Scanner sc = new Scanner(f, StandardCharsets.UTF_8.name())) {
            sc.useDelimiter("\\A");
            return sc.hasNext() ? sc.next() : "";
        }
    }

    static void writeText(File f, String s) throws IOException {
        File tmp = new File(f.getParentFile(), f.getName() + ".tmp");
        try (java.io.FileOutputStream os = new java.io.FileOutputStream(tmp)) {
            os.write(s.getBytes(StandardCharsets.UTF_8));
        }
        if (!tmp.renameTo(f)) {
            // some FUSE setups dislike atomic rename onto an existing file
            if (!f.delete() || !tmp.renameTo(f))
                throw new IOException("cannot write " + f.getPath());
        }
    }
}
